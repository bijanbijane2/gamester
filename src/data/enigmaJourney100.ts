/**
 * Normalizes Persian user input (removes diacritics, unifies Arabic yeh/kaf, trims whitespace)
 */
export function normalizePersianInput(input: string): string {
  if (!input) return '';
  return input
    .trim()
    .toLowerCase()
    .replace(/[\u064B-\u065F\u0670\u200C]/g, '') // remove Arabic harakat and half-spaces
    .replace(/ي/g, 'ی')
    .replace(/ك/g, 'ک')
    .replace(/آ/g, 'ا')
    .replace(/ة/g, 'ه')
    .replace(/[ـ\s\-_]+/g, '');
}

/**
 * Evaluates whether a user's answer matches the accepted answers for a stage
 */
export function checkEnigmaAnswer(stageIndex: number, userAnswer: string): boolean {
  const stage = ENIGMA_STAGES_100[stageIndex];
  if (!stage) return false;

  const normalizedUser = normalizePersianInput(userAnswer);
  if (!normalizedUser || normalizedUser.length === 0) return false;

  return stage.acceptedAnswers.some((ans) => {
    const normalizedAns = normalizePersianInput(ans);
    if (!normalizedAns) return false;
    
    // Exact normalized match
    if (normalizedUser === normalizedAns) return true;
    
    // Substring match with minimum meaningful length
    if (normalizedAns.length >= 3 && normalizedUser.includes(normalizedAns)) return true;
    if (normalizedUser.length >= 4 && normalizedAns.includes(normalizedUser)) return true;
    
    return false;
  });
}
